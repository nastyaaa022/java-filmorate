-- 1. Таблица рейтингов MPA
CREATE TABLE IF NOT EXISTS mpa_rating (
                                          id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          name VARCHAR(50) NOT NULL
    );

-- 2. Таблица жанров
CREATE TABLE IF NOT EXISTS genres (
                                      id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      name VARCHAR(50) NOT NULL
    );

-- 3. Таблица пользователей
CREATE TABLE IF NOT EXISTS users (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     name VARCHAR(100),
    login VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    birthday DATE
    );

-- 4. Таблица фильмов
CREATE TABLE IF NOT EXISTS films (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     name VARCHAR(100) NOT NULL,
    description VARCHAR(200),
    releaseDate DATE,
    duration INT,
    id_mpa_rating INT,
    CONSTRAINT fk_films_mpa FOREIGN KEY (id_mpa_rating) REFERENCES mpa_rating (id) ON DELETE SET NULL
    );

-- 5. Таблица лайков
CREATE TABLE IF NOT EXISTS film_likes (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          id_user BIGINT NOT NULL,
                                          id_film BIGINT NOT NULL,
                                          CONSTRAINT fk_likes_user FOREIGN KEY (id_user) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_likes_film FOREIGN KEY (id_film) REFERENCES films (id) ON DELETE CASCADE
    );

-- 6. Таблица жанров фильма
CREATE TABLE IF NOT EXISTS film_genres (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           id_film BIGINT NOT NULL,
                                           id_genre INT NOT NULL,
                                           CONSTRAINT fk_genres_film FOREIGN KEY (id_film) REFERENCES films (id) ON DELETE CASCADE,
    CONSTRAINT fk_genres_genre FOREIGN KEY (id_genre) REFERENCES genres (id) ON DELETE CASCADE
    );

-- 7. Таблица дружбы
CREATE TABLE IF NOT EXISTS friendships (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           id_user BIGINT NOT NULL,
                                           id_friend BIGINT NOT NULL,
                                           status VARCHAR(50),
    CONSTRAINT fk_friendship_user FOREIGN KEY (id_user) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_friendship_friend FOREIGN KEY (id_friend) REFERENCES users (id) ON DELETE CASCADE
    );

